export function generateRealisticRainfall(lat: number, lon: number, warningLevel: string): number {
  const base: Record<string, { min: number; max: number }> = {
    RED: { min: 200, max: 450 },
    ORANGE: { min: 115, max: 199 },
    YELLOW: { min: 64, max: 114 },
    GREEN: { min: 5, max: 63 },
  };
  const range = base[warningLevel] || base.GREEN;
  // Add geographic variation
  const coastalBonus = (lon > 70 && lon < 80 && lat < 15) ? 50 : 0;
  const himalayanBonus = (lat > 28 && lon > 76 && lon < 90) ? 30 : 0;
  return Math.round(range.min + Math.random() * (range.max - range.min) + coastalBonus + himalayanBonus);
}

export function generateWarningLevel(month: number, lat: number, lon: number): string {
  // Monsoon months: June-September
  const isMonsoon = month >= 6 && month <= 9;
  const isCoastal = (lon > 70 && lon < 80 && lat < 15) || (lon > 80 && lon < 88 && lat < 22);
  const isNE = lat > 24 && lon > 89;

  const rand = Math.random();
  if (isMonsoon) {
    if (isCoastal || isNE) {
      if (rand < 0.15) return "RED";
      if (rand < 0.40) return "ORANGE";
      if (rand < 0.70) return "YELLOW";
      return "GREEN";
    }
    if (rand < 0.08) return "RED";
    if (rand < 0.25) return "ORANGE";
    if (rand < 0.55) return "YELLOW";
    return "GREEN";
  }
  if (rand < 0.03) return "ORANGE";
  if (rand < 0.15) return "YELLOW";
  return "GREEN";
}

export function getImpactSummary(warningLevel: string, pop: number) {
  const multipliers: Record<string, number> = { RED: 1.0, ORANGE: 0.6, YELLOW: 0.3, GREEN: 0.05 };
  const m = multipliers[warningLevel] || 0.05;
  return {
    roadDisruption: warningLevel === "RED" ? "Severe" : warningLevel === "ORANGE" ? "Moderate" : "Minor",
    railService: warningLevel === "RED" ? "Likely cancelled" : warningLevel === "ORANGE" ? "Possible delay" : "Normal",
    cropDamage: warningLevel === "RED" ? "High risk" : warningLevel === "ORANGE" ? "Moderate risk" : "Low risk",
    landslideRisk: warningLevel === "RED" ? "High" : warningLevel === "ORANGE" ? "Medium" : "Low",
    populationAtRisk: Math.round(pop * m),
  };
}
